def wheel2(name, parent, c, loc, r, w, spokes=False):
    b = B()
    b.cyl(r, w, (0, 0, 0), 'Tire', 'x', 14)
    b.cyl(r * (0.82 if spokes else 0.6), w + 0.01, (0, 0, 0), 'Rim' if not spokes else 'Steel', 'x', 10)
    b.cyl(r * 0.15, w + 0.06, (0, 0, 0), 'Dark', 'x', 6)
    return b.obj(name, c, parent, loc)


def wing(b, xr, yr0, yr1, xt, yt0, yt1, z, th, m, zt=None):
    zt = z if zt is None else zt
    for s in (-1, 1):
        v = [(s * xr, yr0, z), (s * xr, yr1, z), (s * xt, yt1, zt), (s * xt, yt0, zt),
             (s * xr, yr0, z + th), (s * xr, yr1, z + th), (s * xt, yt1, zt + th * 0.5), (s * xt, yt0, zt + th * 0.5)]
        b.add(v, [(0, 1, 2, 3), (7, 6, 5, 4), (0, 4, 5, 1), (1, 5, 6, 2), (2, 6, 7, 3), (3, 7, 4, 0)], m)


